const scenario = (compiled: Parameters<typeof runCycle>[0]) => {
  let state = createRunState(compiled);
  const log: unknown[] = [];
  const base = emptyInputs();
  // A sequence through every element: buttons, a level over the limit, an edge, a count, a reset.
  for (let tick = 0; tick < 60; tick += 1) {
    const di = base.di.map((_, index) => (index === 0 ? tick % 10 < 3 : index === 1 ? tick > 40 && tick < 45 : index === 2 ? tick % 8 < 2 : index === 3 ? tick % 6 < 3 : index === 4 ? tick === 50 : false));
    const ai = base.ai.map((_, index) => (index === 0 ? (tick % 20 < 10 ? 7000 : 1000) : 0));
    const result = runCycle(compiled, state, { ...base, di, ai }, 50);
    assert.equal(result.problem, null);
    state = result.state;
    log.push([result.outputs.do.slice(0, 3), state.vars.N]);
  }
  return log;
};

test("the version is pinned, and every older one opens", () => {
  assert.equal(SURFACE_FILE_VERSION, 3);
  assert.deepEqual(SURFACE_FILE_VERSIONS, [1, 2, 3]);
});

test("a version 1 file opens as version 3 with the same program and places, a source put in", () => {
  const result = importLayoutText(FILE_V1);
  assert.ok(result.ok, result.ok ? "" : result.reason);
  if (!result.ok) return;
  assert.equal(result.layout.version, 3);
  assert.equal(result.supplyAdded, true);
  assert.equal(result.layout.program, JSON.parse(FILE_V1).layout.program);
  assert.equal(result.layout.language, "st");
  assert.deepEqual(result.layout.devices.slice(0, 2).map((device) => [device.id, device.x, device.y]), [["knapp-1", 100, 60], ["lampa-1", 800, 560]]);
});

test("a version 2 file with every old Ladder kind loads with the same behaviour as its old text, cycle for cycle", () => {
  const result = importLayoutText(FILE_V2);
  assert.ok(result.ok, result.ok ? "" : result.reason);
  if (!result.ok) return;
  const { layout } = result;
  assert.equal(layout.version, 3);
  assert.equal(layout.outdoorC, -3);
  assert.deepEqual(layout.ladder?.rungs.map((rung) => rung.id), ["r1", "r2", "r3", "r4", "r5"], "the rungs as they were, ids and all");
  assert.deepEqual(layout.ladder?.rungs[0], OLD_LADDER.rungs[0]);
  assert.deepEqual(layout.wires[2].points, [{ x: 200, y: 40 }]);
  assert.equal(layout.wires[2].kind, "signal");
  assert.doesNotMatch(layout.program, /Steg \d/, "written anew in the rungs' numbering");
  assert.match(layout.program, /\(\* Rung 0: Självhållning \*\)/);
  const before = compileProgram(OLD_TEXT), after = compileProgram(layout.program);
  assert.ok(before.ok, before.ok ? "" : before.problem.message);
  assert.ok(after.ok, after.ok ? "" : after.problem.message);
  if (before.ok && after.ok) assert.deepEqual(scenario(after.compiled), scenario(before.compiled));
});

test("what the browser holds opens the same way, a version 2 text in ST stays word for word, and the new version round-trips", () => {
  const stored = loadLayoutText(JSON.stringify(JSON.parse(FILE_V2).layout));
  assert.ok(stored.ok && stored.layout.version === 3 && stored.layout.ladder?.rungs.length === 5);
  const stText = JSON.parse(FILE_V2).layout;
  const inSt = loadLayoutText(JSON.stringify({ ...stText, language: "st" }));
  assert.ok(inSt.ok);
  if (inSt.ok) assert.equal(inSt.layout.program, OLD_TEXT, "a person's text is not touched");
  assert.ok(stored.ok);
  if (!stored.ok) return;
  const again = importLayoutText(exportLayoutText({ ...stored.layout, trendPens: ["var:Motor"] }));
  assert.ok(again.ok);
  if (again.ok) { assert.deepEqual(again.layout.trendPens, ["var:Motor"]); assert.equal(again.layout.program, stored.layout.program); }
});
