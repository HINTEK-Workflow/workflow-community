/**
 * Writes the SQL that moves companies' self-inspection programmes to the current edition of HINTEK's template
 * (2026-10-08, next-wave 6: the older edition must not survive as a company's current programme), in the same way
 * as scripts/forms/builtin-release-migration.ts releases the built-in forms: generated once into prisma/migrations, run by
 * `prisma migrate deploy` in the ordinary deploy step, idempotent and careful. Since 2026-11-20.1 the file is one transaction
 * (BEGIN … COMMIT, docs/drift/MIGRERING-OCH-ATERSTALLNING.md) and its working tables are temporary with ON COMMIT DROP, so the
 * migration check passes it without an approval mark.
 * Usage: npx tsx scripts/self-inspection/template-release-migration.ts > prisma/migrations/<name>/migration.sql
 *
 * The rule is lib/self-inspection/template-upgrade.ts as SQL: a programme is moved only while it is an untouched copy of
 * an earlier edition – templateVersion is an earlier edition, nothing is approved, the same section keys and every body
 * equal to that edition's text (whitespace at the ends aside). Ids, roles, members, people and levels are kept; a role's
 * texts are replaced only where they still read as the earlier edition wrote them. A programme with an approved version or
 * edited text keeps its templateVersion, and both outcomes are written to the company's administration history (the
 * migration's log), one row per programme and edition, never twice.
 *
 * Each edition gets its own migration (20261009100000 for 2026-10-08.1, 20261011400000 for 2026-10-11.1, 20261120120000 for
 * 2026-11-20.1); an earlier migration file is history and is not regenerated.
 */
import { OLD_TEMPLATE_ROLES, OLD_TEMPLATE_VERSIONS, oldTemplateSections } from "../../lib/self-inspection/template-2026-10-07";
import { SELF_INSPECTION_TEMPLATE_VERSION, TEMPLATE_ROLES, TEMPLATE_SECTIONS } from "../../lib/self-inspection/template";

const literal = (value: string) => `'${value.replace(/'/g, "''")}'`;
const actor = "system:hintek";
/** The same characters String.prototype.trim() removes in lib/self-inspection/template-upgrade.ts; btrim alone strips only spaces. */
const trimmed = (expression: string) => `btrim(${expression}, E' \\t\\r\\n')`;
const UPGRADE = '"si_template_upgrade"';
const OLD = '"si_template_old_edition"';

export function templateReleaseSql(): string {
  const version = literal(SELF_INSPECTION_TEMPLATE_VERSION);
  const oldVersions = OLD_TEMPLATE_VERSIONS.map(literal).join(", ");
  const sectionCount = (edition: (typeof OLD_TEMPLATE_VERSIONS)[number]) => oldTemplateSections(edition).length;
  const oldKeys = new Set(OLD_TEMPLATE_VERSIONS.flatMap((edition) => oldTemplateSections(edition).map((section) => section.key)));
  const newKeys = new Set(TEMPLATE_SECTIONS.map((section) => section.key));
  const removed = [...oldKeys].filter((key) => !newKeys.has(key));
  const lines = [
    `-- HINTEK's self-inspection template, edition ${SELF_INSPECTION_TEMPLATE_VERSION}. Generated by scripts/self-inspection/template-release-migration.ts.`,
    "-- Only a programme that is still an untouched copy of an earlier edition is moved (no approved version, every section the earlier edition's text);",
    "-- a programme with an approved version or edited text keeps its edition. Both outcomes are written to the administration history, once per programme.",
    "-- The file is one transaction (Prisma runs it statement by statement): all of it or nothing. Its working tables are temporary and go with the commit.",
    "BEGIN;",
    "",
    "-- The earlier editions' texts, for the equality check.",
    `CREATE TEMP TABLE ${OLD} ("version" TEXT NOT NULL, "key" TEXT NOT NULL, "body" TEXT NOT NULL) ON COMMIT DROP;`,
    `INSERT INTO ${OLD} ("version", "key", "body") VALUES`,
    OLD_TEMPLATE_VERSIONS.flatMap((edition) => oldTemplateSections(edition).map((section) => `  (${literal(edition)}, ${literal(section.key)}, ${literal(section.body)})`)).join(",\n") + ";",
    "",
    "-- The programmes to move: an earlier edition, nothing approved, the edition's number of sections and every section still its text.",
    `CREATE TEMP TABLE ${UPGRADE} ON COMMIT DROP AS`,
    `SELECT p."id", p."organizationId", p."templateVersion"`,
    `FROM "SelfInspectionProgram" p`,
    `WHERE p."templateVersion" IN (${oldVersions})`,
    `  AND NOT EXISTS (SELECT 1 FROM "SelfInspectionVersion" v WHERE v."programId" = p."id")`,
    `  AND (SELECT count(*) FROM "SelfInspectionSection" s WHERE s."programId" = p."id") = (CASE p."templateVersion" ${OLD_TEMPLATE_VERSIONS.map((edition) => `WHEN ${literal(edition)} THEN ${sectionCount(edition)}`).join(" ")} END)`,
    `  AND NOT EXISTS (SELECT 1 FROM "SelfInspectionSection" s WHERE s."programId" = p."id"`,
    `    AND NOT EXISTS (SELECT 1 FROM ${OLD} o WHERE o."version" = p."templateVersion" AND o."key" = s."key" AND ${trimmed(`o."body"`)} = ${trimmed(`s."body"`)}));`,
    "",
    "-- The programmes left as they are, noted in the company's history (the migration's log).",
    `INSERT INTO "AdministrationEvent" ("id", "actorId", "organizationId", "action", "detail", "createdAt")`,
    `SELECT 'si-template-kept-${SELF_INSPECTION_TEMPLATE_VERSION}-' || p."id", ${literal(actor)}, p."organizationId", 'self_inspection_template_kept',`,
    `  'Egenkontrollprogrammet behölls på mallutgåva ' || p."templateVersion" || ': det är fastställt eller har egen text. HINTEK:s mall ' || ${version} || ' gäller för nya program.', CURRENT_TIMESTAMP`,
    `FROM "SelfInspectionProgram" p`,
    `WHERE p."templateVersion" IN (${oldVersions}) AND NOT EXISTS (SELECT 1 FROM ${UPGRADE} u WHERE u."id" = p."id")`,
    `  AND NOT EXISTS (SELECT 1 FROM "AdministrationEvent" e WHERE e."id" = 'si-template-kept-${SELF_INSPECTION_TEMPLATE_VERSION}-' || p."id");`,
    "",
    "-- The sections: the new text in place (same key, same id), the earlier edition's sections that no longer exist removed, the new ones added.",
  ];
  // A section some earlier edition had is updated where the programme has it; a section an earlier edition lacked is added
  // where it is missing (with several earlier editions, a key can be both).
  const everyEditionHas = (key: string) => OLD_TEMPLATE_VERSIONS.every((edition) => oldTemplateSections(edition).some((section) => section.key === key));
  for (const [sortOrder, section] of TEMPLATE_SECTIONS.entries()) {
    if (oldKeys.has(section.key)) lines.push(
      `UPDATE "SelfInspectionSection" s SET "title" = ${literal(section.title)}, "body" = ${literal(section.body)}, "legalRef" = ${literal(section.legalRef)}, "sortOrder" = ${sortOrder}`,
      `FROM ${UPGRADE} u WHERE s."programId" = u."id" AND s."key" = ${literal(section.key)};`,
    );
    if (!everyEditionHas(section.key)) lines.push(
      `INSERT INTO "SelfInspectionSection" ("id", "organizationId", "programId", "key", "title", "body", "legalRef", "sortOrder")`,
      `SELECT u."id" || '-${section.key}', u."organizationId", u."id", ${literal(section.key)}, ${literal(section.title)}, ${literal(section.body)}, ${literal(section.legalRef)}, ${sortOrder}`,
      `FROM ${UPGRADE} u WHERE NOT EXISTS (SELECT 1 FROM "SelfInspectionSection" s WHERE s."programId" = u."id" AND s."key" = ${literal(section.key)});`,
    );
  }
  if (removed.length) lines.push(`DELETE FROM "SelfInspectionSection" s USING ${UPGRADE} u WHERE s."programId" = u."id" AND s."key" IN (${removed.map(literal).join(", ")});`);
  lines.push("", "-- The roles: new name and texts where the role still reads as the earlier edition wrote it; id, members, level and capabilities are kept.");
  for (const role of TEMPLATE_ROLES) {
    const was = OLD_TEMPLATE_ROLES.find((item) => item.key === role.key);
    if (!was) continue;
    lines.push(
      `UPDATE "SelfInspectionRole" r SET "name" = ${literal(role.name)}, "description" = ${literal(role.description)}, "duties" = ${literal(role.duties)}`,
      `FROM ${UPGRADE} u WHERE r."programId" = u."id" AND r."key" = ${literal(role.key)} AND ${trimmed(`r."name"`)} = ${literal(was.name)} AND ${trimmed(`r."description"`)} = ${literal(was.description)} AND ${trimmed(`r."duties"`)} = ${literal(was.duties)};`,
    );
  }
  lines.push(
    "",
    "-- The programme itself, and the history row.",
    `INSERT INTO "AdministrationEvent" ("id", "actorId", "organizationId", "action", "detail", "createdAt")`,
    `SELECT 'si-template-upgraded-${SELF_INSPECTION_TEMPLATE_VERSION}-' || u."id", ${literal(actor)}, u."organizationId", 'self_inspection_template_upgraded',`,
    `  'Egenkontrollprogrammet flyttades från HINTEK:s mall ' || u."templateVersion" || ' till ' || ${version} || ' (orörd kopia, inget fastställt). Roller, personer och kompetens behölls.', CURRENT_TIMESTAMP`,
    `FROM ${UPGRADE} u WHERE NOT EXISTS (SELECT 1 FROM "AdministrationEvent" e WHERE e."id" = 'si-template-upgraded-${SELF_INSPECTION_TEMPLATE_VERSION}-' || u."id");`,
    `UPDATE "SelfInspectionProgram" p SET "templateVersion" = ${version}, "revision" = p."revision" + 1, "updatedAt" = CURRENT_TIMESTAMP`,
    `FROM ${UPGRADE} u WHERE p."id" = u."id";`,
    "",
    "COMMIT;",
  );
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] && /template-release-migration/.test(process.argv[1])) process.stdout.write(templateReleaseSql());
