export type SurfaceExample = { id: string; title: string; group: "industri" | "fastighet"; line: string; layout: Layout };

const ref = (text: string): TerminalRef => { const [device, terminal] = text.split(":"); return { device, terminal }; };
const wires = (pairs: readonly [string, string][]): Wire[] => pairs.map(([from, to], index) => ({ id: `w${index + 1}`, from: ref(from), to: ref(to) }));
const device = (id: string, kind: DeviceKindId, x: number, y: number, label: string, options: Record<string, string> = {}): DeviceInst => ({ id, kind, x, y, label, options });

const program = (lines: readonly string[]) => lines.join("\n");
